import static org.xvm.javajit.TypeSystem.AT;

/**
 * Builds the concrete implementation of an annotated composition, not its widened callable type.
 */
public class AnnotatedBuilder extends CommonBuilder {
    public AnnotatedBuilder(TypeSystem typeSystem, Artifact art) {
        super(typeSystem, art);

        assert art.type().isAnnotated();
        baseType = art.type().removeAnnotations().ensureAccess(Access.PRIVATE);
    }

    /**
     * The base type (sans annotations); PRIVATE access.
     */
    private final TypeConstant baseType;

    @Override
    protected boolean hasRuntimeType() {
        return true;
    }

    @Override
    public TypeConstant getSuperType() {
        return baseType;
    }

    @Override
    protected TypeConstant getConstructorOwnerType() {
        return baseType;
    }

    @Override
    public boolean shouldGenerate(IdentityConstant id) {
        IdentityConstant owner = id instanceof PropertyConstant
                ? id.getClassIdentity()
                : id.getNamespace();
        return owner.equals(thisId)
                ? id instanceof MethodConstant m && (m.isConstructor() || m.isValidator())
                : super.shouldGenerate(id);
    }

    @Override
    protected void assembleMethods(ClassBuilder classBuilder) {
        // annotation constructors are not part of our TypeInfo and need to be assembled manually
        assembleAnnotationConstructors(classBuilder);

        super.assembleMethods(classBuilder);
    }

    /**
     * Assemble annotation constructor bodies on the annotated implementation class.
     */
    private void assembleAnnotationConstructors(ClassBuilder classBuilder) {
        for (AnnotationConstructor[] constructors : collectAnnotationConstructors()) {
            for (AnnotationConstructor constructor : constructors) {
                MethodInfo method = constructor.method();
                if (method.getHead().getMethodStructure().isNoOp()) {
                    continue;
                }

                String      name = annotationConstructorName(constructor);
                JitCtorDesc jmd  = constructor.desc();

                if (jmd.isOptimized) {
                    assembleMethodWrapper(classBuilder, name, jmd);
                    name += OPT;
                }

                BuildContext bctx = new BuildContext(this, method.getTypeInfo(), method, jmd, thisType);
                doAssembleMethod(classBuilder, bctx, method, name,
                        jmd.isOptimized ? jmd.optimizedMD : jmd.standardMD,
                        ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC);
            }
        }
    }

    @Override
    protected void assembleMethod(ClassBuilder classBuilder, MethodInfo method, String jitName,
                                  JitMethodDesc jmd) {
        // the constructor is generated by the base class; skip it here; however a corresponding
        // the assembleInstantiator() will still be called by the CommonBuilder
        if (!method.isConstructor()) {
            super.assembleMethod(classBuilder, method, jitName, jmd);
        }
    }

    @Override
    protected void assembleInstantiator(ClassBuilder classBuilder, MethodInfo constructor,
                                        String jitName, JitCtorDesc ctorDesc) {
        JitCtorDesc baseDesc = (JitCtorDesc) Builder.convertConstructToNew(
                                    typeInfo, art.CD(), ctorDesc);

        // a reusable Java class must support every combination of annotation constructor overloads
        // for this base constructor; collectAnnotationConstructors() groups them by annotation;
        // each row of combinations selects one constructor overload from each annotation's
        // candidate row and defines one instantiator
        //
        // consider the scenario with two constructors on A1 and three on A0:
        //    annotation A1 into B {
        //        construct(Int value)    {...}
        //        construct(String value) {...}
        //    }
        //    annotation A0 into B {
        //        construct(Int value)    {...}
        //        construct(String value) {...}
        //        construct(UInt value)   {...}
        //    }
        //
        // for @A1 @A0 B, we need six instantiator augmentations (combinations):
        //    $new@0$0@1$0(Ctx, TypeConstant, baseArgs..., Int    v1, Int    v0)
        //    $new@0$0@1$1(Ctx, TypeConstant, baseArgs..., Int    v1, String v0)
        //    $new@0$0@1$2(Ctx, TypeConstant, baseArgs..., Int    v1, UInt   v0)
        //    $new@0$1@1$0(Ctx, TypeConstant, baseArgs..., String v1, Int    v0)
        //    $new@0$1@1$1(Ctx, TypeConstant, baseArgs..., String v1, String v0)
        //    $new@0$1@1$2(Ctx, TypeConstant, baseArgs..., String v1, UInt   v0)
        //
        // standard and optimized Java entry points are handled separately

        AnnotationConstructor[][] candidates   = collectAnnotationConstructors();
        int[][]                   combinations = collectColumnIndexes(candidates);

        // the example has two annotation rows, containing two and three constructors:
        //    candidates[0] = [A1(Int), A1(String)]
        //    candidates[1] = [A0(Int), A0(String), A0(UInt)]
        // combinations has six instantiator rows and two annotation columns;
        // column 0 selects overload 0 or 1 of A1, and column 1 selects overload 0, 1 or 2 of A0

        for (int[] indexes : combinations) {
            List<AnnotationConstructor> selected   = new ArrayList<>(candidates.length);
            JitCtorDesc                 instorDesc = baseDesc;
            StringBuilder               instorName = new StringBuilder(jitName);

            // on the third pass indexes is [0,2], so the rows contribute Int, UInt
            for (int i = 0; i < candidates.length; i++) {
                AnnotationConstructor annoCtor = candidates[i][indexes[i]];
                selected.add(annoCtor);
                instorDesc = instorDesc.appendParams(annoCtor.desc());
                instorName.append(annotationConstructorName(annoCtor));
            }

            // that pass emits $new@0$0@1$2, with A1 and A0 arguments in that order
            assembleNew(classBuilder, constructor, instorName.toString(), instorDesc, selected);
        }
    }

    /**
     * Collect all constructor overloads for each annotation in this type's composition.
     *
     * <p>The outer array follows annotation invocation order: A1, then A0 for {@code @A1 @A0 B}.
     * Each inner array contains that annotation's {@code construct} overloads, including no-op
     * constructors, sorted by method identity string. With Int and String overloads on A1 and Int,
     * String and UInt overloads on A0, the two rows have two and three entries:
     * <pre>
     * [[A1(Int), A1(String)],
     *  [A0(Int), A0(String), A0(UInt)]]
     * </pre>
     *
     * <p>Each entry records the annotation's outer-array index, constructor MethodInfo, and
     * JitCtorDesc for this annotated type. These groups supply both synthetic constructor body
     * assembly and the indexed selection of one overload per annotation for each instantiator.
     *
     * @return constructor overload candidates grouped by annotation
     */
    private AnnotationConstructor[][] collectAnnotationConstructors() {
        Annotation[]              annos = typeInfo.getMixinAnnotations();
        AnnotationConstructor[][] all   = new AnnotationConstructor[annos.length][];
        for (int i = 0; i < annos.length; i++) {
            TypeInfo info = annos[i].getAnnotationType().ensureAccess(Access.PRIVATE).ensureTypeInfo();

            MethodConstant[] ids = info.findMethods("construct", -1, MethodKind.Constructor)
                    .toArray(MethodConstant[]::new);
            Arrays.sort(ids, Comparator.comparing(MethodConstant::getValueString));
            if (ids.length == 0) {
                throw new IllegalStateException("Missing annotation constructor for " + annos[i]);
            }

            AnnotationConstructor[] ctors = new AnnotationConstructor[ids.length];
            for (int j = 0; j < ids.length; j++) {
                MethodInfo method = info.getMethodById(ids[j], false);
                ctors[j] = new AnnotationConstructor(i, method,
                        (JitCtorDesc) method.getJitDesc(this, thisType));
            }
            all[i] = ctors;
        }
        return all;
    }

    /**
     * Generate all combinations of column indexes, selecting one column from each input row.
     *
     * <p>Each result row contains one column index for each input row. The number of result rows
     * is the product of the input row lengths. For input rows of lengths 2 and 3, the result has
     * six rows and two columns:
     * <pre>
     * [[0,0],
     *  [0,1],
     *  [0,2],
     *  [1,0],
     *  [1,1],
     *  [1,2]]
     * </pre>
     * The index for the last input row varies fastest. With no input rows, the result contains
     * one empty row; an input row with no columns produces no result rows.
     *
     * @param rows  the input rows; element values are ignored
     *
     * @return all column-index combinations, with one column per input row
     */
    private static int[][] collectColumnIndexes(Object[][] rows) {
        int count = 1;
        for (Object[] row : rows) {
            count = Math.multiplyExact(count, row.length);
        }

        int[][] combinations = new int[count][];
        if (count == 0) {
            return combinations;
        }
        combinations[0] = new int[rows.length]; // all zeros
        for (int row = 1; row < count; row++) {
            int[] indexes = combinations[row - 1].clone();

            // advance the rightmost available choice and reset the following choices;
            // from [0,2], column 1 resets to zero and column 0 advances, producing [1,0]
            for (int i = indexes.length - 1; i >= 0; i--) {
                if (++indexes[i] < rows[i].length) {
                    break;
                }
                indexes[i] = 0;
            }
            combinations[row] = indexes;
        }
        return combinations;
    }

    @Override
    protected void invokeAnnotationConstructors(CodeBuilder code, List<AnnotationConstructor> constructors,
                                                int ctxSlot, int cctxSlot, int thisSlot, int paramIx) {
        for (AnnotationConstructor constructor : constructors) {
            JitCtorDesc    jmd    = constructor.desc();
            JitParamDesc[] params = jmd.isOptimized ? jmd.optimizedParams : jmd.standardParams;

            if (constructor.method().getHead().getMethodStructure().isNoOp()) {
                // skip unused the parameters
                paramIx += params.length;
                continue;
            }

            if (jmd.hasCtorCtx() && cctxSlot < 0) {
                cctxSlot = code.allocateLocal(TypeKind.REFERENCE);
                code.aload(ctxSlot)
                    .invokevirtual(CD_Ctx, "ctorCtx", md(CD_CtorCtx))
                    .astore(cctxSlot);
            }

            code.aload(ctxSlot);
            if (jmd.hasCtorCtx()) {
                code.aload(cctxSlot);
            }
            code.aload(thisSlot);
            for (JitParamDesc pd : params) {
                load(code, pd.cd, code.parameterSlot(paramIx++));
            }
            code.invokestatic(art.CD(), annotationConstructorName(constructor) +
                    (jmd.isOptimized ? OPT : ""), jmd.isOptimized ? jmd.optimizedMD : jmd.standardMD);
        }
    }

    /**
     * Resolve the instantiator for the overloads selected by the unstripped annotation applications.
     */
    public static JitCallDesc getInstantiatorCall(BuildContext bctx, TypeConstant targetType,
                                                 String baseName, JitCtorDesc baseDesc) {
        Builder       builder = bctx.builder;
        JitCtorDesc   newDesc = baseDesc;
        StringBuilder newName = new StringBuilder(baseName);
        int           index   = 0;

        for (Annotation annotation : targetType.ensureTypeInfo().getMixinAnnotations()) {
            MethodInfo constructor = findAnnotationConstructor(bctx, annotation);

            newDesc = newDesc.appendParams(constructor.getJitDesc(
                    builder, targetType.ensureAccess(Access.STRUCT)));
            newName.append(annotationConstructorName(builder, index++, constructor));
        }
        return JitCallDesc.static_(builder.getICDesc(targetType), newName.toString(), newDesc, false);
    }

    /**
     * Load annotation arguments after the base constructor arguments.
     */
    public static void loadAnnotationConstructorArgs(BuildContext bctx, CodeBuilder code,
                                                     TypeConstant targetType) {
        Builder builder = bctx.builder;
        for (Annotation annotation : targetType.ensureTypeInfo().getMixinAnnotations()) {
            MethodInfo    ctor = findAnnotationConstructor(bctx, annotation);
            JitMethodDesc jmd  = ctor.getJitDesc(builder, targetType.ensureAccess(Access.STRUCT));
            Constant[]    args = annotation.getParams();

            bctx.loadCallArguments(code, jmd, i -> {
                Constant value = i < args.length ? args[i] : null;
                if (value == null || value instanceof RegisterConstant register &&
                        register.getRegisterIndex() == Op.A_DEFAULT) {
                    return null;
                }

                return value instanceof RegisterConstant register
                        ? bctx.loadArgument(code, register.getRegisterIndex())
                        : builder.loadConstant(bctx, code, value);
            }, targetType);
        }
    }

    /**
     * Find the constructor overload for a specific annotation application, such as {@code @A(value)}.
     *
     * <p>Match the application's argument types against the constructors on the annotation's own
     * type. Register argument types come from the supplied build context; explicit default markers
     * leave their argument types unspecified.
     *
     * @return the matching Ecstasy constructor's MethodInfo
     *
     * @throws IllegalStateException if no matching constructor is found
     */
    private static MethodInfo findAnnotationConstructor(BuildContext bctx, Annotation annotation) {
        Constant[]     args     = annotation.getParams();
        TypeConstant[] argTypes = new TypeConstant[args.length];

        for (int i = 0; i < args.length; i++) {
            Constant value = args[i];
            if (value instanceof RegisterConstant register) {
                if (register.getRegisterIndex() != Op.A_DEFAULT) {
                    argTypes[i] = bctx.getRegisterInfo(register.getRegisterIndex()).type();
                }
            } else if (value instanceof PropertyClassTypeConstant property) {
                argTypes[i] = property.getProperty().getValueType(bctx.pool(), null);
            } else {
                argTypes[i] = value.getType();
            }
        }

        TypeInfo       info = annotation.getAnnotationType().ensureAccess(Access.PRIVATE).ensureTypeInfo();
        MethodConstant id   = info.findConstructor(argTypes);
        if (id == null) {
            throw new IllegalStateException("Missing annotation constructor for " + annotation);
        }
        return info.getMethodById(id, false);
    }

    /**
     * Obtain the synthetic annotation constructor method name, using '@' for AT in these examples.
     * The first annotation's constructors are "@0$0", "@0$1", "@0$2", etc.; the second annotation's
     * first constructor is "@1$0". The same name is appended to the instantiator name, for example
     * "$new@0$0".
     */
    private String annotationConstructorName(AnnotationConstructor constructor) {
        return annotationConstructorName(this, constructor.annoIndex(), constructor.method());
    }

    private static String annotationConstructorName(Builder builder, int index, MethodInfo method) {
        // every annotation segment includes an explicit constructor ordinal, including zero
        String name    = method.ensureJitMethodName(builder.typeSystem);
        String ordinal = name.equals("construct") ? "0" : name.substring("construct$".length());
        return AT + Integer.toString(index) + '$' + ordinal;
    }
}
